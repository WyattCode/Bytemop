  init: call('app:init'),
  disk: call('disk:info'),
  scan: call('rules:scan'),
  scanAdmin: call('rules:scanAdmin'),
  details: call('rules:details'),
  clean: call('rules:clean'),
  runs: call('runs:list'),
  restore: call('runs:restore'),
  purge: call('runs:purge'),
  purgeAll: call('runs:purgeAll'),
  history: call('history:list'),
  historyExport: call('history:export'),
  aboutInfo: call('about:info'),
  openDataDir: call('about:openData'),
  scheduleGet: call('schedule:get'),
  scheduleApply: call('schedule:apply'),
  scheduleTest: call('schedule:testNotify'),
  startupList: call('startup:list'),
  startupSet: call('startup:set'),
  startupReveal: call('startup:reveal'),
  exclusions: call('exclusions:list'),
  addExclusion: call('exclusions:add'),
  removeExclusion: call('exclusions:remove'),
  repairExclusions: call('exclusions:repair'),
  pickExclusion: call('exclusions:pick'),
  privacyScan: call('privacy:scan'),
  privacySites: call('privacy:sites'),
  privacyKeepAdd: call('privacy:keepAdd'),
  privacyKeepRemove: call('privacy:keepRemove'),
  privacyClean: call('privacy:clean'),
